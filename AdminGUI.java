    private void plantTreeBtnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_plantTreeBtnActionPerformed
        // TODO add your handling code here:
        //Checks if queue is empty
        if(GreenTreesApp.treeQueue.isEmpty()) {
            JOptionPane.showMessageDialog(this,"Queue empty");
            return;
        }
        //Plants trees from queue, FIFO
        TreePlantRequest request = (TreePlantRequest) GreenTreesApp.treeQueue.dequeue();
        Volunteer v = request.getVolunteer();
        v.setTotalTreesPlanted(v.getTotalTreesPlanted() + 1);
        GreenTreesApp.adminLogs.push("Tree planted for " + v.getName()); //log for admin
        JOptionPane.showMessageDialog(this, "Tree planted for " + v.getName());
        updateQueueInfo();
    }//GEN-LAST:event_plantTreeBtnActionPerformed

    private void viewAllBtnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_viewAllBtnActionPerformed
        // TODO add your handling code here:
        //Displays all volunteers in searchTf
        String result = "";
        for(Volunteer v : GreenTreesApp.volunteer) {
            result += v.getName() + " | ID: " + v.getUserID() + " | Trees: " + v.getTotalTreesPlanted() + " | Balance: €" + v.getBalance() + "\n";
        }
        searchTf.setText(result);
    }//GEN-LAST:event_viewAllBtnActionPerformed

    private void updateQueueInfo() {
        //Updates queue info
        int queueSize = GreenTreesApp.treeQueue.size();
        treesWaitingLbl.setText(String.valueOf(queueSize));
        TreePlantRequest next = (TreePlantRequest) GreenTreesApp.treeQueue.frontElement(); //peeks at next request
        if(next != null) {
            nextRequestLbl.setText(next.getVolunteer().getName() + " -> " + next.getTree().getName());
        }
        else {
            nextRequestLbl.setText("None");
        }
    }
