    private void deleteBtnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_deleteBtnActionPerformed
        // TODO add your handling code here
        int id = Integer.parseInt(userIDTf.getText());
        for(int i = 0; i < GreenTreesApp.volunteer.size(); i++) {
            //Deletes user from volunteer list
            if(GreenTreesApp.volunteer.get(i).getUserID() == id){
                String name = GreenTreesApp.volunteer.get(i).getName();
                GreenTreesApp.volunteer.remove(i);
                GreenTreesApp.adminLogs.push("User deleted: " + name);
                JOptionPane.showMessageDialog(this, "User deleted");
                userIDTf.setText("");
                return;
            }
        }
        JOptionPane.showMessageDialog(this, "User not found");
    }//GEN-LAST:event_deleteBtnActionPerformed

    private void searchBtnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_searchBtnActionPerformed
        // TODO add your handling code here:
        //Searches for volunteer by ID and appends info to searchTf
        int id = Integer.parseInt(searchIDTf.getText());
        for(Volunteer v : GreenTreesApp.volunteer) {
            if(v.getUserID() == id) {
                String result = "Name: " + v.getName() + "\nID: " + v.getUserID() + "\nTrees Planted: " + v.getTotalTreesPlanted() + "\nBalance: €" + v.getBalance();
                searchTf.setText(result);
                GreenTreesApp.adminLogs.push("User searched: " + v.getName()); //log for admin
                return;
            }
        }
        searchTf.setText("Volunteer not found.");
    }//GEN-LAST:event_searchBtnActionPerformed

