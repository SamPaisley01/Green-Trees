    private void createUserBtnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_createUserBtnActionPerformed
        // TODO add your handling code here:
        String name = nameTf.getText();
        int id = Integer.parseInt(IDTf.getText());
        String password = passwordTf.getText();
        String address = addressTf.getText();
        String phone = phoneTf.getText();
        
        //Validation
        for(Volunteer v : GreenTreesApp.volunteer) {
            if(v.getUserID() == id) {
                JOptionPane.showMessageDialog(this, "User ID already exists");
                return;
            }
        }

        //Create volunteer and add to list and leaderboard
        Volunteer v = new Volunteer(name, id, password, address, phone);
        GreenTreesApp.volunteer.add(v);
        GreenTreesApp.leaderboard.add(v);
        
        GreenTreesApp.adminLogs.push("User created: " + name);//log for admin
        JOptionPane.showMessageDialog(this, "Volunteer created");
        
        //Clear text fields
        nameTf.setText("");
        IDTf.setText("");
        passwordTf.setText("");
        addressTf.setText("");
        phoneTf.setText("");
    }//GEN-LAST:event_createUserBtnActionPerformed

