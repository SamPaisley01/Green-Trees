    private void updateLogs(){
        if(GreenTreesApp.adminLogs.isEmpty()) {
            totalLogsTf.setText("0");
            treesPlantedTf.setText("-");
            userSearchTf.setText("-");
            userCreatedTf.setText("-");
            userDeletedTf.setText("-"); 
            return;
        }
        int total = GreenTreesApp.adminLogs.size();
        totalLogsTf.setText(String.valueOf(GreenTreesApp.adminLogs.size()));
        String logs = GreenTreesApp.adminLogs.displayStack();
        if(logs.contains("Tree planted")) {
            treesPlantedTf.setText("Yes");
        }   
        if(logs.contains("User searched")) {
            userSearchTf.setText("Yes");
        }
        if(logs.contains("User created")) {
            userCreatedTf.setText("Yes");
        }
        if(logs.contains("User deleted")) {
            userDeletedTf.setText("Yes");
        }
    }
