    private void lastLogBtnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_lastLogBtnActionPerformed
        // TODO add your handling code here:
        if(GreenTreesApp.adminLogs.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this,"No logs to remove");
            return;
        }
        GreenTreesApp.adminLogs.pop();
        updateLogs();
    }//GEN-LAST:event_lastLogBtnActionPerformed

